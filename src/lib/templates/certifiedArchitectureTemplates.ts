export interface TemplateFilterSelection {
  tier?: 'All' | ArchitectureTemplateTier;
  level: 'All' | ArchitectureTemplateLevel;
  type: 'All' | ArchitectureTemplateType;
  kind: 'All' | ArchitectureTemplateKind;
  useCase: 'All' | ArchitectureTemplateUseCase;
  collection?: 'All' | ArchitectureTemplateCollection;
  layoutArchetype?: 'All' | ArchitectureTemplateLayoutArchetype;
  search?: string;
}

const RETIRED_TEMPLATE_ID_ALIASES: Record<string, string> = {};

export function getCertifiedArchitectureTemplateById(
  rawId: string | null | undefined
): CertifiedArchitectureTemplate | undefined {
  if (!rawId) return undefined;
  const trimmed = String(rawId).trim();
  const stripped = trimmed.replace(/^(?:arch_tpl_|canonical_|template_|#)/i, '');
  const normalized = RETIRED_TEMPLATE_ID_ALIASES[stripped] || stripped;
  const low = normalized.toLowerCase();
  return CERTIFIED_ARCHITECTURE_TEMPLATES.find(
    (t) =>
      t.id.toLowerCase() === low ||
      t.id.toLowerCase() === normalized.padStart(2, '0').toLowerCase() ||
      t.slug.toLowerCase() === trimmed.toLowerCase() ||
      t.serialTag.toLowerCase() === low ||
      t.canonicalTag.toLowerCase() === low ||
      (t.suiteSerial && t.suiteSerial.toLowerCase() === low)
  );
}

export function filterCertifiedArchitectureTemplates(
  filters: TemplateFilterSelection
): readonly CertifiedArchitectureTemplate[] {
  const q = (filters.search || '').trim().toLowerCase();
  const tr = filters.tier || 'All';
  const col = filters.collection || 'All';
  const arch = filters.layoutArchetype || 'All';
  return CERTIFIED_ARCHITECTURE_TEMPLATES.filter((t) => {
    if (tr !== 'All' && t.tier !== tr) return false;
    if (filters.level !== 'All' && t.level !== filters.level) return false;
    if (filters.type !== 'All' && t.type !== filters.type) return false;
    if (filters.kind !== 'All' && t.kind !== filters.kind) return false;
    if (filters.useCase !== 'All' && t.useCase !== filters.useCase) return false;
    if (col !== 'All' && t.collection !== col) return false;
    if (arch !== 'All' && t.layoutArchetype !== arch) return false;
    if (q) {
      const hay = `${t.serialTag} ${t.suiteSerial || ''} ${t.id} ${t.tier} ${t.primaryAlternativeRef || ''} ${t.canonicalTag} ${t.silhouetteTag || ''} ${t.categoryTag || ''} ${t.styleTag || ''} ${t.publicationStatus || ''} ${t.collection} ${t.layoutArchetype} ${t.headerTag} ${t.title} ${t.pattern} ${t.level} ${t.type} ${t.kind} ${t.useCase} ${t.summary}`.toLowerCase();
      if (!hay.includes(q)) return false;
    }
    return true;
  });
}

export function computeDynamicFacetCounts(filters: TemplateFilterSelection) {
  const countWith = (override: Partial<TemplateFilterSelection>) =>
    filterCertifiedArchitectureTemplates({ ...filters, ...override }).length;

  const tiers: Record<string, number> = { All: countWith({ tier: 'All' }) };
  for (const tr of ARCHITECTURE_TEMPLATE_TIERS) {
    tiers[tr] = countWith({ tier: tr });
  }

  const levels: Record<string, number> = { All: countWith({ level: 'All' }) };
  for (const lvl of ARCHITECTURE_TEMPLATE_LEVELS) {
    levels[lvl] = countWith({ level: lvl });
  }

  const types: Record<string, number> = { All: countWith({ type: 'All' }) };
  for (const tp of ARCHITECTURE_TEMPLATE_TYPES) {
    types[tp] = countWith({ type: tp });
  }

  const kinds: Record<string, number> = { All: countWith({ kind: 'All' }) };
  for (const kd of ARCHITECTURE_TEMPLATE_KINDS) {
    kinds[kd] = countWith({ kind: kd });
  }

  const useCases: Record<string, number> = { All: countWith({ useCase: 'All' }) };
  for (const uc of ARCHITECTURE_TEMPLATE_USE_CASES) {
    useCases[uc] = countWith({ useCase: uc });
  }

  const collections: Record<string, number> = { All: countWith({ collection: 'All' }) };
  for (const c of ARCHITECTURE_TEMPLATE_COLLECTIONS) {
    collections[c] = countWith({ collection: c });
  }

  const layoutArchetypes: Record<string, number> = { All: countWith({ layoutArchetype: 'All' }) };
  for (const la of ARCHITECTURE_TEMPLATE_LAYOUT_ARCHETYPES) {
    layoutArchetypes[la] = countWith({ layoutArchetype: la });
  }

  return { tiers, levels, types, kinds, useCases, collections, layoutArchetypes };
}

export async function fetchImmutableTemplateXml(
  template: CertifiedArchitectureTemplate
): Promise<string> {
  const res = await fetch(template.drawioUrl, { cache: 'force-cache' });
  if (!res.ok) {
    throw new Error(`Failed to load template XML for #${template.id}`);
  }
  return String(await res.text());
}

export async function cloneArchitectureTemplateInstance(
  template: CertifiedArchitectureTemplate,
  createdStudio = 'dashboard'
): Promise<{ instanceId: string; xml: string; template: CertifiedArchitectureTemplate }> {
  const res = await fetch('/api/diagrams', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      name: template.title,
      templateId: template.id,
      comment: `Cloned from immutable Template ${template.serialTag} · #${template.id} (${template.tier} · ${template.canonicalTag})`,
      prompt: template.summary,
      aiReasoning: `Cloned from Certified Architecture Template ${template.serialTag} · #${template.id} (${template.tier} • ${template.canonicalTag} • ${template.level} • ${template.type} • ${template.kind} • ${template.useCase} • ${template.layoutArchetype}). Original template remains intact; all mutations apply strictly to this unique clone ID.`,
      businessUsecase: template.useCase,
      technicalUsecase: `${template.type} · ${template.kind}`,
      architectureType: `arch_tpl_${template.id}`,
      createdStudio,
    }),
  });
  const data = await res.json();
  const instanceId = String(data?.diagram?.id || data?.id || '').trim();
  if (!res.ok || !instanceId) {
    throw new Error(data?.error || `Failed to clone Template #${template.id}`);
  }
  const clonedXml =
    typeof data?.version?.xml_content === 'string' && data.version.xml_content.includes('<mxCell')
      ? data.version.xml_content
      : typeof data?.diagram?.xml_content === 'string' && data.diagram.xml_content.includes('<mxCell')
      ? data.diagram.xml_content
      : await fetchImmutableTemplateXml(template);

  return { instanceId, xml: clonedXml, template };
}
